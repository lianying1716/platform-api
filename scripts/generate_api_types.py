#!/usr/bin/env python3
"""Generate the frontend's transport types from FastAPI's OpenAPI document.

The repository intentionally keeps the generator dependency-free: the schema
surface used by the UI is a small Pydantic subset, and adding an npm codegen
tool just to emit interfaces would create another lockfile and supply-chain
surface.  The generated file is checked for drift in CI/tests.

Usage:
    python3 scripts/generate_api_types.py          # write web/src/api.generated.ts
    python3 scripts/generate_api_types.py --check  # fail if the file is stale
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "web" / "src" / "api.generated.ts"


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def _literal(value: Any) -> str:
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return json.dumps(value, ensure_ascii=False)


def _union(items: list[str]) -> str:
    unique = list(dict.fromkeys(items))
    return " | ".join(unique) if unique else "never"


def _type(schema: dict[str, Any], *, indent: int = 0) -> str:
    if "$ref" in schema:
        return _ref_name(str(schema["$ref"]))
    if "anyOf" in schema:
        return _union([_type(item, indent=indent) for item in schema["anyOf"]])
    if "oneOf" in schema:
        return _union([_type(item, indent=indent) for item in schema["oneOf"]])
    if "allOf" in schema:
        return " & ".join(_type(item, indent=indent) for item in schema["allOf"])
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return _union([_literal(item) for item in schema["enum"]])
    kind = schema.get("type")
    if kind == "array":
        item_type = _type(schema.get("items") or {}, indent=indent)
        return f"({item_type})[]" if " | " in item_type else f"{item_type}[]"
    if kind == "object" or "properties" in schema:
        properties = schema.get("properties") or {}
        if not properties:
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict):
                return f"Record<string, {_type(extra, indent=indent)}>"
            return "Record<string, unknown>"
        pad = "  " * (indent + 1)
        required = set(schema.get("required") or [])
        lines = ["{"]
        for name, child in properties.items():
            optional = "" if name in required else "?"
            lines.append(f"{pad}{json.dumps(name, ensure_ascii=False)}{optional}: {_type(child, indent=indent + 1)}")
        lines.append("  " * indent + "}")
        return "\n".join(lines)
    if kind == "string":
        return "string"
    if kind == "integer" or kind == "number":
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    return "unknown"


def _safe_comment(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip()


def render(schema: dict[str, Any]) -> str:
    components = (schema.get("components") or {}).get("schemas") or {}
    lines = [
        "// AUTO-GENERATED by scripts/generate_api_types.py. Do not edit by hand.",
        "// Source: FastAPI app.openapi(); regenerate after changing Pydantic schemas.",
        "",
    ]
    for name in sorted(components):
        body = components[name] or {}
        title = _safe_comment(str(body.get("title") or name))
        kind = body.get("type")
        if kind == "object" or "properties" in body:
            lines.append(f"/** {title} */")
            lines.append(f"export interface {name} {_type(body)}")
        else:
            lines.append(f"/** {title} */")
            lines.append(f"export type {name} = {_type(body)}")
        lines.append("")

    paths = schema.get("paths") or {}
    response_aliases: list[str] = []
    response_map: list[str] = []
    request_aliases: list[str] = []
    request_map: list[str] = []
    required_body_operations: list[str] = []
    path_params_map: list[str] = []
    query_params_map: list[str] = []
    total_header_operations: list[str] = []
    routes: list[str] = []
    lines.append("export interface ApiPaths {")
    for path in sorted(paths):
        methods = paths[path] or {}
        operations = []
        for method, operation in methods.items():
            if method.lower() not in {"get", "post", "put", "patch", "delete"}:
                continue
            operation_id = operation.get("operationId") or f"{method}_{path}"
            operations.append(f"    {json.dumps(method.upper())}: {json.dumps(operation_id)}")
            routes.append(
                f"  {json.dumps(operation_id)}: "
                f"{{ method: {json.dumps(method.upper())}, path: {json.dumps(path)} }},"
            )
            responses = operation.get("responses") or {}
            success = next(
                (
                    responses.get(code)
                    for code in ("200", "201", "202")
                    if isinstance(responses.get(code), dict)
                ),
                None,
            )
            content = (success or {}).get("content") or {}
            response_schema = (content.get("application/json") or {}).get("schema") or {}
            if response_schema:
                alias = re.sub(r"[^A-Za-z0-9]+", "_", operation_id).strip("_") + "Response"
                response_aliases.append(
                    f"export type {alias} = {_type(response_schema)}"
                )
                response_map.append(f"  {json.dumps(operation_id)}: {alias}")
            request_body = operation.get("requestBody") or {}
            request_content = (request_body.get("content") or {}).get("application/json") or {}
            request_schema = request_content.get("schema") or {}
            if request_schema:
                body_alias = re.sub(r"[^A-Za-z0-9]+", "_", operation_id).strip("_") + "Body"
                request_aliases.append(
                    f"export type {body_alias} = {_type(request_schema)}"
                )
                request_map.append(f"  {json.dumps(operation_id)}: {body_alias}")
                if request_body.get("required") is True:
                    required_body_operations.append(f"  {json.dumps(operation_id)}: true")

            path_props: dict[str, dict[str, Any]] = {}
            query_props: dict[str, dict[str, Any]] = {}
            path_required: list[str] = []
            for parameter in operation.get("parameters") or []:
                location = parameter.get("in")
                name = str(parameter.get("name") or "")
                if not name:
                    continue
                param_schema = parameter.get("schema") or {"type": "string"}
                if location == "path":
                    path_props[name] = param_schema
                    if parameter.get("required", True):
                        path_required.append(name)
                elif location == "query":
                    query_props[name] = param_schema
            if path_props:
                path_type = _type(
                    {
                        "type": "object",
                        "properties": path_props,
                        "required": path_required,
                    }
                )
                path_params_map.append(f"  {json.dumps(operation_id)}: {path_type}")
            if query_props:
                query_required = [
                    str(parameter.get("name"))
                    for parameter in operation.get("parameters") or []
                    if parameter.get("in") == "query" and parameter.get("required") is True
                ]
                query_type = _type(
                    {
                        "type": "object",
                        "properties": query_props,
                        "required": query_required,
                    }
                )
                query_params_map.append(f"  {json.dumps(operation_id)}: {query_type}")
            if "X-Total-Count" in ((success or {}).get("headers") or {}):
                total_header_operations.append(f"  {json.dumps(operation_id)}: true")
        if operations:
            lines.append(f"  {json.dumps(path)}: {{")
            lines.extend(operations)
            lines.append("  }")
    lines.append("}")
    if response_aliases:
        lines.extend(["", "// Typed success responses keyed by FastAPI operationId."])
        lines.extend(dict.fromkeys(response_aliases))
    if response_map:
        lines.extend(["", "export interface ApiResponses {", *response_map, "}"])
    if request_aliases:
        lines.extend(["", "// Typed request bodies keyed by FastAPI operationId."])
        lines.extend(dict.fromkeys(request_aliases))
    if request_map:
        lines.extend(["", "export interface ApiRequestBodies {", *request_map, "}"])
    if required_body_operations:
        lines.extend(
            [
                "",
                "export interface ApiRequiredBodyOperations {",
                *required_body_operations,
                "}",
            ]
        )
    if path_params_map:
        lines.extend(["", "export interface ApiPathParams {", *path_params_map, "}"])
    if query_params_map:
        lines.extend(["", "export interface ApiQueryParams {", *query_params_map, "}"])
    if total_header_operations:
        lines.extend(
            [
                "",
                "// Operations whose total is carried by X-Total-Count.",
                "export interface ApiTotalHeaderOperations {",
                *total_header_operations,
                "}",
            ]
        )
    if routes:
        lines.extend(
            [
                "",
                "// Operation IDs from FastAPI, used by apiCall() so URL drift fails typecheck.",
                "export const apiRoutes = {",
                *routes,
                "} as const",
                "export type ApiOperation = keyof typeof apiRoutes",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def build() -> str:
    # Importing app.main must never touch the real database.  The test suite
    # already establishes this env contract; keep the generator safe by itself.
    os.environ.setdefault("PLATFORM_DATABASE_URL", "sqlite:///:memory:")
    os.environ.setdefault("PLATFORM_CREDENTIAL_ENC_KEY", "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA=")
    sys.path.insert(0, str(ROOT))
    # Re-exec under the project virtualenv when invoked with the system Python.
    # Production servers usually have no FastAPI on the system interpreter, so
    # requiring callers to remember `.venv/bin/python` would make the drift gate
    # easy to skip.
    try:
        from app.main import app  # type: ignore[import-not-found]
    except ModuleNotFoundError as exc:
        if exc.name not in {"fastapi", "pydantic", "sqlalchemy"}:
            raise
        venv_python = ROOT / ".venv" / "bin" / "python"
        if not venv_python.is_file() or Path(sys.executable).resolve() == venv_python.resolve():
            raise
        import subprocess

        result = subprocess.run(
            [str(venv_python), str(Path(__file__).resolve()), *sys.argv[1:]],
            cwd=ROOT,
            check=False,
        )
        # Raise SystemExit, not return: build() must produce the generated text,
        # never a process exit code.
        raise SystemExit(result.returncode)

    return render(app.openapi())




def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated output is stale")
    args = parser.parse_args()
    text = build()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"stale generated API types: {OUTPUT}", file=sys.stderr)
            print("run `python3 scripts/generate_api_types.py` and commit the result", file=sys.stderr)
            return 1
        print(f"API types are up to date: {OUTPUT}")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
